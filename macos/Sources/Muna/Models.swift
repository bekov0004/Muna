/// The Tray: files dropped on the capsule wait here (as references, not copies).
final class TrayModel: ObservableObject {
    private let store = TrayStore()
    @Published private(set) var files: [URL] = []

    init() {
        store.keep = Settings.bool(Settings.keepTrayKey, default: true)
        files = store.files
    }

    func add(_ urls: [URL]) {
        store.add(urls)
        files = store.files
    }

    func remove(_ url: URL) {
        store.remove([url])
        files = store.files
    }

    func clear() {
        store.clear()
        files = store.files
    }

    func refresh() {
        store.dropMissing()
        files = store.files
    }

    /// "Keep the Tray after a restart" changed in the menu.
    func applyKeepSetting() {
        store.keep = Settings.bool(Settings.keepTrayKey, default: true)
    }
}

/// The clipboard history: watches the pasteboard and keeps what was copied (MunaCore's ClipboardHistory).
final class ClipboardModel: ObservableObject {
    private let history = ClipboardHistory()
    @Published private(set) var items: [ClipItem] = []
    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Copies that password managers and the like mark as not to be kept.
    private static let secretTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    init() {
        history.keepHistory = Settings.bool(Settings.keepClipboardKey, default: true)
        items = history.items
    }

    var keepHistory: Bool {
        get { history.keepHistory }
        set {
            history.keepHistory = newValue
            Settings.set(Settings.keepClipboardKey, newValue)
        }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.secretTypes) else { return }
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            history.add(files: urls)
        } else if let text = pasteboard.string(forType: .string) {
            history.add(text: text)
        } else {
            return
        }
        items = history.items
    }

    /// Puts an item back on the clipboard (Cmd+V pastes it).
    func copy(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        if let files = item.files {
            pasteboard.writeObjects(files.compactMap { URL(string: $0) as NSURL? })
        } else if let text = item.text {
            pasteboard.setString(text, forType: .string)
        }
        changeCount = pasteboard.changeCount
        // it moves to the top, as if copied again
        if let text = item.text {
            history.add(text: text)
        } else if let files = item.files {
            history.add(files: files.compactMap { URL(string: $0) })
        }
        items = history.items
    }

    func togglePinned(_ item: ClipItem) {
        history.setSaved(item, !item.saved)
        items = history.items
    }

    func remove(_ item: ClipItem) {
        history.remove(item)
        items = history.items
    }

    func clear() {
        history.clear()
        items = history.items
    }
}

/// The calendar: today's and tomorrow's events from the Mac's calendars (EventKit).
final class CalendarModel: ObservableObject {
    struct Event: Identifiable, Equatable {
        let id: String
        let title: String
        let start: Date
        let end: Date
        let allDay: Bool
        let color: NSColor?
    }

    enum Access { case unknown, granted, denied }

    @Published private(set) var events: [Event] = []
    @Published private(set) var access = Access.unknown
    private let store = EKEventStore()
    private var timer: Timer?
    private var observer: NSObjectProtocol?

    func start() {
        let status = EKEventStore.authorizationStatus(for: .event)
        if Self.isGranted(status) {
            access = .granted
            load()
        } else if status == .notDetermined {
            access = .unknown
        } else {
            access = .denied
        }
        observer = NotificationCenter.default.addObserver(forName: .EKEventStoreChanged, object: store, queue: .main) { [weak self] _ in
            self?.load()
        }
        timer = Timer.scheduledTimer(withTimeInterval: 300, repeats: true) { [weak self] _ in self?.load() }
    }

    /// Asks macOS for the calendars (the first time the panel shows them).
    func requestAccess() {
        let done: (Bool, Error?) -> Void = { [weak self] granted, _ in
            DispatchQueue.main.async {
                self?.access = granted ? .granted : .denied
                if granted { self?.load() }
            }
        }
        if #available(macOS 14.0, *) {
            store.requestFullAccessToEvents(completion: done)
        } else {
            store.requestAccess(to: .event, completion: done)
        }
    }

    private static func isGranted(_ status: EKAuthorizationStatus) -> Bool {
        if #available(macOS 14.0, *) {
            return status == .fullAccess
        }
        return status == .authorized
    }

    func load() {
        guard access == .granted else { return }
        let calendar = Calendar.current
        let start = calendar.startOfDay(for: Date())
        guard let end = calendar.date(byAdding: .day, value: 2, to: start) else { return }
        let predicate = store.predicateForEvents(withStart: start, end: end, calendars: nil)
        let now = Date()
        events = store.events(matching: predicate)
            .filter { $0.endDate > now }
            .sorted { ($0.isAllDay ? 0 : 1, $0.startDate) < ($1.isAllDay ? 0 : 1, $1.startDate) }
            .prefix(12)
            .map { Event(id: $0.eventIdentifier ?? UUID().uuidString, title: $0.title ?? "Event", start: $0.startDate,
                         end: $0.endDate, allDay: $0.isAllDay, color: $0.calendar?.color) }
    }

    /// The next event that has not started yet (for the closed capsule).
    var next: Event? { events.first { !$0.allDay && $0.start > Date() } }
}
